// instead of manually adding Authorization: Bearer ... to every API call, an interceptor does it for you. 
// Every outgoing HTTP request passes through it.

import { HttpInterceptorFn } from '@angular/common/http';
import { inject } from '@angular/core';
import { AuthService } from '../services/auth.service';

export const authInterceptor: HttpInterceptorFn = (req, next) => {
  const authService = inject(AuthService);
  const token = authService.getToken();

  // If no token (not logged in), the original request passes through unchanged — this lets login/register calls work without a token
  if (token) {
    const clonedReq = req.clone({
      setHeaders: {
        Authorization: `Bearer ${token}`
      }
    });
    return next(clonedReq);
  }

  return next(req);
};
